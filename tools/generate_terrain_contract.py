"""Generate Python's type-only terrain contract from the authoritative C# enum."""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/CableRoutePlanner.Domain/TerrainKind.cs"
OUTPUT = ROOT / "tools/GeodataPreparation/terrain_kinds.py"


def render(source: str) -> str:
    body = re.search(r"public enum TerrainKind\s*{([^}]+)}", source)
    if body is None:
        raise ValueError("TerrainKind enum declaration is missing")
    names = []
    for member in body.group(1).split(","):
        member = member.strip()
        if not member:
            continue
        if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", member):
            raise ValueError(f"Unsupported TerrainKind member: {member!r}")
        names.append(member)
    if not names:
        raise ValueError("TerrainKind enum is empty")
    values = "".join(f'    "{name}",\n' for name in names)
    return (
        '"""Generated by tools/generate_terrain_contract.py; edit Domain/TerrainKind.cs."""\n'
        "\nfrom typing import Literal\n\nTerrainKind = Literal[\n" + values + "]\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    expected = render(SOURCE.read_text(encoding="utf-8"))
    if options.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            parser.exit(
                1,
                "TerrainKind Python contract is stale; run tools/generate_terrain_contract.py\n",
            )
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
